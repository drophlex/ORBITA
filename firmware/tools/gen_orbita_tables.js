// ÓRBITA FM-1: the web version's own note choice (docs/classic/app.js note()), evaluated here exactly as the browser does,
// for every geometry x scale x phase x voice x step -> firmware-src/firmware/src/orbita_tables.h. The firmware plays
// the same notes as the web version, with no floating point on the device.
const fs = require('fs'), path = require('path');
const app = fs.readFileSync(path.join(__dirname, '../../docs/classic/app.js'), 'utf8');
const scales = eval(app.match(/const scales=(\[\[.*?\]\])/)[1]), roots = eval(app.match(/roots=(\[[^\]]*\])/)[1]);
const scenes = eval(app.match(/const scenes=(\[[\s\S]*?\n\]);/)[1]);
function note(v, s, geo, sc, phase) {   // docs/app.js note(v,s), with its selects as arguments
  const scl = scales[sc]; let a = s * Math.PI / 8 + phase * v * Math.PI / 8;
  let n = Math.floor((1 + [Math.sin(a * (1 + v)), Math.cos(a * 2) * Math.sin(a), Math.sin(a + Math.sin(3 * a))][geo]) * scl.length * .48);
  return roots[sc] + v * 12 + scl[n];
}
let out = `/* SPDX-License-Identifier: GPL-3.0-only\n * ÓRBITA: generated by tools/gen_orbita_tables.js from docs/classic/app.js (the web version); do not edit.\n * ORB_NOTE[geometry][scale][phase][voice][step]: the MIDI note the web version plays there. */\n#pragma once\n`;
out += 'static const uint8_t ORB_NOTE[3][3][16][3][16] = {\n';
for (let g = 0; g < 3; g++) { out += ' {\n'; for (let c = 0; c < 3; c++) { out += '  {\n'; for (let p = 0; p < 16; p++) {
  out += '   {' + [0, 1, 2].map(v => '{' + Array.from({ length: 16 }, (_, s) => note(v, s, g, c, p)).join(',') + '}').join(',') + '},\n'; }
  out += '  },\n'; } out += ' },\n'; }
out += '};\n';
out += '/* the scenes: name, description, BPM, geometry, scale, density, phase, FM ratio x2 */\n';
out += 'typedef struct { const char *name, *desc; uint8_t bpm, geo, scale, dens, phase, ratio2; } orb_scene_t;\n';
const EN = { 'Anillo de Mérida': ['MERIDA RING', 'A SPACIOUS BASS, TWO BELLS CROSSING'], 'Cristal sesgado': ['SKEWED CRYSTAL', 'OFFBEAT METAL, A FIVE-PETAL ROSE'],
  'Deriva lunar': ['LUNAR DRIFT', 'A SLOW PULSE, OPEN RESONANCES'], 'Ácido discreto': ['DISCRETE ACID', 'DENSE SIXTEENTHS, BRIGHT FM'] };
out += 'static const orb_scene_t ORB_SCENES[' + scenes.length + '] = {\n' + scenes.map(s => `    {"${EN[s[0]][0]}", "${EN[s[0]][1]}", ${s[2]}, ${s[3]}, ${s[4]}, ${s[5]}, ${s[6]}, ${Math.round(s[7] * 2)}},`).join('\n') + '\n};\n';
out += `#define ORB_NSCENES ${scenes.length}u\n`;
fs.writeFileSync(path.join(__dirname, '../firmware-src/firmware/src/orbita_tables.h'), out);
console.log('orbita_tables.h:', scenes.length, 'scenes, 2304 notes; roots', roots.join(' '));
// the test's expectations: the web version's pattern() for every density and phase (tests/orbita_test.c)
{
  const pat = (den, phase) => [0, 1, 2].map(v => Array.from({ length: 16 }, (_, s) => ((s + phase * v) * Math.min(16, Math.max(1, den + [-3, 0, 2][v]))) % 16 < Math.min(16, Math.max(1, den + [-3, 0, 2][v])) ? 1 : 0));
  let t = '/* generated by tools/gen_orbita_tables.js from docs/classic/app.js pattern(): ORB_WEB_MASK[density - 3][phase][voice] (bit s: step s hits) */\n#pragma once\n';
  t += 'static const uint16_t ORB_WEB_MASK[12][16][3] = {\n';
  for (let d = 3; d <= 14; d++) { t += ' {'; for (let p = 0; p < 16; p++) t += '{' + pat(d, p).map(r => r.reduce((a, b, i) => a | (b << i), 0)).join(',') + '},'; t += '},\n'; }
  t += '};\n';
  fs.writeFileSync(path.join(__dirname, '../firmware-src/tests/orbita_expect.h'), t);
}
